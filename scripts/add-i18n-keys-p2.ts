    const filePath = path.join(MESSAGES_DIR, `${lang}.json`);
    const content = JSON.parse(fs.readFileSync(filePath, 'utf8'));

    // Add sptCommon section
    content.sptCommon = sptCommon[lang];

    // Add taxTools section
    content.taxTools = taxTools[lang];

    // Add counterparties section
    content.counterparties = counterparties[lang];

    // Add aiUsage section
    content.aiUsage = aiUsage[lang];

